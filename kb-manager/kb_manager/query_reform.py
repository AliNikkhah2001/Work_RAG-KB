QUERY_TYPE_KEYWORDS = {
    "keyword_only": ["امتیاز", "اعتباری", "تسهیلات", "بازپرداخت", "ضامن", "گزارش", "اعتبارسنجی"],
    "conversational": ["می‌شه", "می‌تونم", "یه", "داشتم", "سلام", "ببخشید", "راستی"],
    "typo": ["میشه", "میکنن", "دسترسى", "اعتبارى", "قرارداد", "گزراش"],
    "reworded": ["نقش", "چیه", "چی", "تفاوت", "مراحل", "مرحله"],
}


def detect_query_type(query: str) -> str:
    """Heuristic detection of query type for adaptive retrieval."""
    query_lower = query.lower()
    
    scores = {}
    for qtype, keywords in QUERY_TYPE_KEYWORDS.items():
        score = sum(1 for kw in keywords if kw in query_lower)
        if score > 0:
            scores[qtype] = score
    
    if not scores:
        return "general"
    
    return max(scores, key=scores.get)


