@dataclass
class ReformulatedQuery:
    """A reformulated query with metadata."""
    query: str
    query_type: str
    original_query: str
    metadata: Optional[dict] = None


@dataclass
class HyDEDocument:
    """Hypothetical document generated by HyDE."""
    content: str
    query: str
    score: float = 0.0


# ---------------------------------------------------------------------------
# HyDE Generator
# ---------------------------------------------------------------------------

class HyDEGenerator:
    """Generates hypothetical documents (HyDE) for query expansion — DEPRECATED.

    Use ``kb_manager.hyde.HyDEGenerator`` (httpx + SentenceTransformer) as the
    canonical implementation. This class is kept for backward compat and now
    warns on instantiation (B13/B14 fix).
    """

    def __init__(
        self,
        llm_client: Any,
        prompt_template: str = _HYDE_PROMPT_FA,
        max_length: int = 512,
    ) -> None:
        import warnings

        warnings.warn(
            "kb_manager.query_reform.HyDEGenerator is deprecated; use kb_manager.hyde.HyDEGenerator",
            DeprecationWarning,
            stacklevel=2,
        )
        self._llm = llm_client
        self._prompt_template = prompt_template
        self._max_length = max_length
        self._cache: dict[str, HyDEDocument] = {}

    def generate(self, query: str) -> HyDEDocument:
        """Generate a hypothetical document for the query."""
        # Check cache
        cache_key = f"hyde:{query}"
        if cache_key in self._cache:
            return self._cache[cache_key]

        prompt = self._prompt_template.format(query=query)
        
        try:
            # Use the LLM client to generate hypothetical document
            response = self._llm.generate(
                prompt,
                max_tokens=self._max_length,
                temperature=0.3,
            )
            
            # Extract content from response
            content = self._extract_content(response)
            
            doc = HyDEDocument(content=content, query=query)
            self._cache[cache_key] = doc
            return doc
            
        except Exception as e:
            logger.warning("HyDE generation failed for query '%s': %s", query, e)
            # Return empty document on failure
            return HyDEDocument(content="", query=query)

    def _extract_content(self, response: Any) -> str:
        """Extract text content from LLM response."""
        if isinstance(response, str):
            return response.strip()
        if isinstance(response, dict):
            return response.get("text", "").strip()
        if hasattr(response, "text"):
            return response.text.strip()
        return str(response).strip()

    def embed_and_search(
        self,
        query: str,
        dense_index: Any,
        top_k: int = 10,
    ) -> List[tuple[str, float]]:
        """Generate HyDE doc, embed it, and search dense index (F7 fix: use correct API)."""
        hyde_doc = self.generate(query)
        if not hyde_doc.content:
            return []

        # DenseSemanticIndex.search expects string, not embedding; use content directly
        # (canonical HyDE uses embedding vector via dense._matrix @ hyde_vec in search.py)
        return dense_index.search(hyde_doc.content, top_k=top_k)


