class MultiQueryGenerator:
    """Generates multiple query reformulations for robust retrieval.

    Based on "A Surprisingly Simple yet Effective Multi-Query Rewriting Method
    for Conversational Passage Retrieval" (Kostric & Balog, 2024).
    Uses beam search to generate diverse reformulations.
    """

    def __init__(
        self,
        llm_client: Any,
        prompt_template: str = _MULTI_QUERY_PROMPT_FA,
        num_queries: int = 6,
        beam_size: int = 5,
    ) -> None:
        import warnings

        warnings.warn(
            "kb_manager.query_reform.MultiQueryGenerator is placeholder; use canonical retrieval or implement beam search",
            UserWarning,
            stacklevel=2,
        )
        self._llm = llm_client
        self._prompt_template = prompt_template
        self._num_queries = num_queries
        self._beam_size = beam_size
        self._cache: dict[str, List[ReformulatedQuery]] = {}

    def generate(self, query: str) -> List[ReformulatedQuery]:
        """Generate multiple reformulated queries."""
        cache_key = f"multi_query:{query}"
        if cache_key in self._cache:
            return self._cache[cache_key]

        prompt = self._prompt_template.format(
            query=query,
            num_queries=self._num_queries,
        )

        try:
            response = self._llm.generate(
                prompt,
                max_tokens=512,
                temperature=0.4,
            )
            
            content = self._extract_json(response)
            queries = self._parse_queries(content, query)
            
            self._cache[query] = queries
            return queries
            
        except Exception as e:
            logger.warning("Multi-query generation failed for '%s': %s", query, e)
            # Return at least the original query
            return [ReformulatedQuery(
                query=query,
                query_type="original",
                original_query=query,
            )]

    def _extract_json(self, response: Any) -> str:
        """Extract JSON from LLM response (F22 fix: strict, non-greedy)."""
        text = str(response).strip()
        # Try to parse first balanced JSON array via raw_decode
        try:
            start = text.find("[")
            if start != -1:
                decoder = json.JSONDecoder()
                obj, end = decoder.raw_decode(text[start:])
                return json.dumps(obj, ensure_ascii=False)
        except Exception:
            pass
        # Fallback: non-greedy regex
        match = re.search(r"\[.*?\]", text, re.DOTALL)
        if match:
            return match.group(0)
        return text

    def _parse_queries(self, json_text: str, original_query: str) -> List[ReformulatedQuery]:
        """Parse JSON array into ReformulatedQuery objects."""
        try:
            data = json.loads(json_text)
            queries = []
            for item in data:
                if isinstance(item, dict) and "query" in item:
                    queries.append(ReformulatedQuery(
                        query=item["query"],
                        query_type=item.get("type", "unknown"),
                        original_query=original_query,
                    ))
            return queries if queries else [
                ReformulatedQuery(query=original_query, query_type="original", original_query=original_query)
            ]
        except json.JSONDecodeError:
            return [ReformulatedQuery(query=original_query, query_type="original", original_query=original_query)]


