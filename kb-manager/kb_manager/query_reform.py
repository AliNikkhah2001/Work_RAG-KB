def create_hyde_generator(llm_client: Any) -> HyDEGenerator:
    """Create HyDE generator with default Persian prompt."""
    return HyDEGenerator(llm_client=llm_client)


def create_multi_query_generator(llm_client: Any) -> MultiQueryGenerator:
    """Create multi-query generator with default Persian prompt."""
    return MultiQueryGenerator(llm_client=llm_client)


def get_query_reform_components(llm_client: Any) -> tuple[HyDEGenerator, MultiQueryGenerator]:
    """Get both HyDE and multi-query generators."""
    return (
        HyDEGenerator(llm_client=llm_client),
        MultiQueryGenerator(llm_client=llm_client),
    )