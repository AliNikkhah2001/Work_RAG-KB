# RRF Fusion
# ---------------------------------------------------------------------------

def reciprocal_rank_fusion(
    ranked_lists: List[List[tuple[str, float]]],
    k: int = 60,
    top_k: Optional[int] = None,
) -> List[tuple[str, float]]:
    """Reciprocal Rank Fusion (RRF) for combining multiple ranked lists.

    Args:
        ranked_lists: List of (doc_id, score) tuples, each list sorted by relevance.
        k: RRF constant (default 60).
        top_k: Optional limit on output size.

    Returns:
        List of (doc_id, fused_score) sorted by fused score descending.
    """
    fused_scores: dict[str, float] = {}
    
    for ranked_list in ranked_lists:
        for rank, (doc_id, _) in enumerate(ranked_list):
            rrf_score = 1.0 / (k + rank + 1)
            fused_scores[doc_id] = fused_scores.get(doc_id, 0) + rrf_score

    # Sort by fused score
    fused = sorted(fused_scores.items(), key=lambda x: x[1], reverse=True)
    
    if top_k:
        fused = fused[:top_k]
    
    return fused


def weighted_rrf(
    ranked_lists: List[List[tuple[str, float]]],
    weights: List[float],
    k: int = 60,
    top_k: Optional[int] = None,
) -> List[tuple[str, float]]:
    """Weighted Reciprocal Rank Fusion.

    Args:
        ranked_lists: List of ranked lists.
        weights: Weight for each list (should sum to 1.0).
        k: RRF constant.
        top_k: Optional limit.

    Returns:
        Fused ranked list.
    """
    if len(ranked_lists) != len(weights):
        raise ValueError("Number of ranked lists must match number of weights")

    fused_scores: dict[str, float] = {}
    
    for weight, ranked_list in zip(weights, ranked_lists):
        for rank, (doc_id, _) in enumerate(ranked_list):
            rrf_score = weight / (k + rank + 1)
            fused_scores[doc_id] = fused_scores.get(doc_id, 0) + rrf_score

    fused = sorted(fused_scores.items(), key=lambda x: x[1], reverse=True)
    
    if top_k:
        fused = fused[:top_k]
    
    return fused


